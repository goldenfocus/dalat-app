import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import en from "@/messages/en.json";
vi.mock("next-intl", () => ({ useLocale: () => "en", useTranslations: () => (key: string, args: Record<string, unknown> = {}) => Object.entries(args).reduce((s,[k,v])=>s.replace(`{${k}}`,String(v)),(en.eventPractice as Record<string,string>)[key] || key) }));
vi.mock("@/lib/hooks/use-viewer", () => ({ useViewer: () => ({profile:null}) }));
vi.mock("@/lib/i18n/routing", () => ({usePathname:()=>"/practice/rehearsal", useRouter:()=>({replace:vi.fn()}), Link: ({children,...props}: React.ComponentProps<"a">) => <a {...props}>{children}</a>}));
vi.mock("qrcode", () => ({default:{toDataURL:vi.fn().mockResolvedValue("data:image/png;base64,cXJjb2Rl")}}));
import { PracticeRehearsal } from "./practice-rehearsal";
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
it("starts empty, shows the QR and check-in actions, and keeps check-in and tables in one workspace", async()=>{
  const fetcher=vi.fn();vi.stubGlobal("fetch",fetcher);
  render(<PracticeRehearsal/>);
  expect(screen.getByRole("tab",{name:"Check-in"})).toHaveAttribute("aria-selected","true");
  expect(await screen.findByText("0/50 checked")).toBeVisible();
  expect(await screen.findByRole("img",{name:"Sample QR"})).toBeVisible();
  fireEvent.click(screen.getByRole("button",{name:"Confirm Alex is here"}));
  await screen.findByText("1/50 checked");
  fireEvent.click(screen.getByRole("button",{name:"Confirm Sam is here"}));
  await screen.findByText("2/50 checked");
  fireEvent.click(screen.getByRole("tab",{name:"Tables"}));
  expect(await screen.findByRole("button",{name:"Start Game"})).toBeDisabled();
  expect(screen.queryByRole("region",{name:/Table \d/})).toBeNull();
  fireEvent.click(screen.getByRole("tab",{name:"Check-in"}));
  fireEvent.click(await screen.findByRole("button",{name:"Mark Alex absent"}));
  await screen.findByText("1/50 checked");
  fireEvent.click(screen.getByRole("button",{name:"Confirm Alex is here"}));
  await screen.findByText("2/50 checked");
  fireEvent.click(screen.getByRole("button",{name:"Confirm Mai is here"}));
  await screen.findByText("3/50 checked");
  fireEvent.click(screen.getByRole("tab",{name:"Tables"}));
  expect(await screen.findByRole("button",{name:"Start Game"})).toBeEnabled();
  expect(screen.getByRole("region",{name:/Table \d/})).toBeVisible();
  fireEvent.click(screen.getByRole("tab",{name:"Guest view"}));
  expect(await screen.findByRole("button",{name:"Play"})).toBeEnabled();
  expect(fetcher).not.toHaveBeenCalled();
});
it("supports keyboard tab changes and reset always returns to zero checked in", async()=>{
  render(<PracticeRehearsal/>);
  await screen.findByText("0/50 checked");
  fireEvent.keyDown(screen.getByRole("tab",{name:"Check-in"}),{key:"ArrowRight"});
  expect(screen.getByRole("tab",{name:"Tables"})).toHaveAttribute("aria-selected","true");
  fireEvent.click(screen.getByRole("button",{name:"Reset sample event"}));
  await waitFor(()=>expect(screen.getByRole("tab",{name:"Check-in"})).toHaveAttribute("aria-selected","true"));
  expect(await screen.findByText("0/50 checked")).toBeVisible();
});
