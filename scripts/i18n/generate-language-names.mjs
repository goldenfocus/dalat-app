/** Refresh the bundled Unicode CLDR language names using Node's full ICU data. */
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../../lib/arrival/languages.ts", import.meta.url), "utf8");
const codes = [...source.split("as const;")[0].matchAll(/"([a-z]{2})"/g)].map(match => match[1]);
const locales = ["en", "vi", "ko", "zh", "ru", "fr", "ja", "ms", "th", "de", "es", "id"];
const names = locales.map(locale => new Intl.DisplayNames([locale], { type: "language", fallback: "none" }));
// These names are absent from the Malay CLDR catalog in Node's ICU data.
const malayNames = { cr: "Cree", ho: "Hiri Motu", ik: "Inupiaq", oj: "Ojibwa", pi: "Pali" };
const rows = codes.map(code => {
  const labels = names.map((display, index) => {
    const name = display.of(code) || (locales[index] === "ms" ? malayNames[code] : undefined);
    if (!name || name === code) throw new Error(`Missing ${locales[index]} name for ${code}`);
    return name;
  });
  const native = new Intl.DisplayNames([code], { type: "language", fallback: "none" }).of(code) || labels[0];
  return `  ${code}: ${JSON.stringify([...labels, native])},`;
});
writeFileSync(new URL("../../lib/arrival/language-names.ts", import.meta.url), `// Unicode CLDR names bundled for browsers with incomplete Intl.DisplayNames data.\n// Generated by scripts/i18n/generate-language-names.mjs; do not edit by hand.\nexport const LANGUAGE_NAME_LOCALES = ${JSON.stringify(locales)} as const;\n// Columns follow LANGUAGE_NAME_LOCALES, then the native language name.\nexport const LANGUAGE_NAMES = {\n${rows.join("\n")}\n} as const;\n`);
